"""Build the browser's static research bundle from versioned, separate JSON files."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'research/2026-10-12/data'
names = ['events', 'sources', 'locations', 'units', 'conflicts', 'hypotheses', 'person', 'family-transport']
data = {name.replace('-', '_'): json.loads((DIRECTORY / f'{name}.json').read_text(encoding='utf-8')) for name in names}
data['awards'] = json.loads((ROOT / 'research/onderscheidingen.json').read_text(encoding='utf-8'))

data['revision'] = '2026-10-12'
data['presentation'] = json.loads((ROOT / 'research/presentation.json').read_text(encoding='utf-8'))
data['report_url'] = 'research/2026-10-12/RAPPORT.md'
data['rights_url'] = 'research/2026-10-12/RECHTEN.md'
data['historical_map_url'] = 'https://maps.lib.utexas.edu/maps/historical/ambon_1943.jpg'
data['source_images'] = {
    'S01': 'assets/08-stamboek-volledig.jpg',
    'S03': 'assets/03-IMG-20210321-WA0010-1-.jpg',
    'S04': 'assets/05-IMG-20210321-WA0013-1-.jpg',
    'S05': 'assets/06-IMG-20210321-WA0014-1-.jpg',
    'S06': 'assets/04-IMG-20210321-WA0009-1-.jpg',
    'S07': 'assets/02-IMG-20210321-WA0017-1-.jpg',
    'S08': 'assets/07-IMG-20210321-WA0019-1-.jpg',
    'S11': 'assets/21-nfis-tual-landing-en-gevangenneming.jpg',
    'S12': 'assets/23-nfis-vluchtroute-ceram-tual.jpg',
    'S13': 'assets/24-nfis-depot-bataljon-ambon.jpg',
    'S14': 'assets/15-archief-456-0014.jpg',
    'S17': 'assets/17-jacar-C08030264000-scan-1.jpg',
    'S18': 'assets/22-jacar-kei-juli-1942-scan-0290.jpg'
}
# Family-supplied archive originals are published with their own provenance manifest.
archive_manifest = ROOT / 'assets/archief/2.13.132-1164/manifest.json'
archive_text = {r['id']: r for r in json.loads((ROOT / 'research/archiefbronnen-1947.json').read_text(encoding='utf-8'))}
data['source_details'] = {}
for i, image in enumerate(json.loads(archive_manifest.read_text(encoding='utf-8')), 33):
    data['source_images'][f'S{i:02}'] = 'assets/archief/2.13.132-1164/' + image['original']
    data['source_details'][f'S{i:02}'] = {**archive_text[image['id']], 'crop': 'assets/archief/2.13.132-1164/' + image['crop'], 'original': data['source_images'][f'S{i:02}'], 'source_url': image['source_url']}
for s in data['sources']:
    s.pop('local_path', None)
for f in data['family_transport']:
    f.pop('source_path', None)
# Public reading copy: research questions and assessments stay in the local backlog.
publication = json.loads((ROOT / 'research/publicatie.json').read_text(encoding='utf-8'))
data['events'] = [e for e in data['events'] if e['evidence_level'] != 'D']
for event in data['events']:
    event['notes'] = publication['event_texts'][event['id']]
for source in data['sources']:
    source.pop('note', None)
data['sources'] = [s for s in data['sources'] if s['kind'] != 'catalogue_only']
public_ids = {s['id'] for s in data['sources']}
for event in data['events']:
    event['source_ids'] = [i for i in event['source_ids'] if i in public_ids]
data['presentation'] = {'chapters': publication['chapters'], 'contexts': publication['contexts']}
for chapter in data['presentation']['chapters']:
    chapter['source_ids'] = [i for i in chapter['source_ids'] if i in public_ids]
for context in data['presentation']['contexts'].values():
    context['ids'] = [i for i in context['ids'] if i in public_ids]
for details in data['source_details'].values():
    details.pop('boundary', None)
    details['context'] = publication['archive_contexts'][details['id']]
for unit in data['units']:
    unit.pop('notes', None)
for award in data['awards']:
    award.pop('boundary', None)
for key in ['hypotheses', 'conflicts', 'person', 'family_transport', 'report_url']:
    data.pop(key, None)
OUT = ROOT / 'data/research.js'
OUT.parent.mkdir(exist_ok=True)
OUT.write_text('/* Generated by scripts/build-data.py; edit the JSON sources. */\n'
               + 'window.KNIL_RESEARCH = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{OUT.relative_to(ROOT)}: {len(data["events"])} events, {len(data["sources"])} sources')
